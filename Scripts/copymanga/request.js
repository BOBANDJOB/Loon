// BOBANDJOB: same-origin request bridge for the Byaidu reader.
// No arbitrary proxy: only this site's source pages/scripts and the original reader APIs.
(function () {
    const SITE = /^(?:[a-z0-9-]+\.)*(?:copymanga\.(?:com|org|net|info|site|tv)|mangacopy\.com|copy20\.com|2025copy\.com)$/i;
    const BRIDGE = '/__loon_copymanga__/fetch';
    const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/138.0.0.0 Safari/537.36 Edg/138.0.0.0';
    const incoming = parseURL($request.url);
    if (!incoming || !SITE.test(incoming.host)) return $done({});
    const userAgent = String(header($request.headers, 'user-agent'));
    if (/\b(?:Macintosh|Windows NT|X11|CrOS)\b/i.test(userAgent) &&
        !/\b(?:iPhone|iPad|iPod|Android|Mobile)\b/i.test(userAgent)) return $done({});
    if (incoming.path === '/__loon_copymanga__/manifest.webmanifest' && !/^api\./.test(incoming.host)) {
        if ($request.method !== 'GET') return $done({});
        return $done({ response: { status: 200, headers: {
            'Content-Type': 'application/manifest+json; charset=utf-8', 'Cache-Control': 'no-cache'
        }, body: JSON.stringify({
            id: '/__loon_copymanga__/webapp', name: '拷贝漫画', short_name: '拷贝漫画',
            start_url: '/h5/index', scope: '/', display: 'standalone',
            background_color: '#212121', theme_color: '#212121'
        }) } });
    }

    function parseURL(value) {
        const match = /^https:\/\/([a-z0-9.-]+)(\/[^#\s]*)?$/i.exec(String(value));
        if (!match || /[\r\n\\]/.test(value)) return null;
        return { url: String(value), host: match[1].toLowerCase(), origin: 'https://' + match[1].toLowerCase(), path: (match[2] || '/').split('?')[0] };
    }
    function header(headers, key) {
        const name = Object.keys(headers || {}).find(k => k.toLowerCase() === key);
        return name ? headers[name] : '';
    }
    function respond(status, value) {
        $done({ response: { status, headers: { 'Content-Type': 'application/json; charset=utf-8', 'Cache-Control': 'no-store' }, body: JSON.stringify(value) } });
    }
    function fail(status, message) { respond(status, { error: message }); }
    function allowed(target, method) {
        if (!target || /(?:^|\/)\.\.(?:\/|$)|%2e|%2f|%5c/i.test(target.path)) return false;
        if (target.host === incoming.host && !/^api\./i.test(target.host)) {
            return method === 'GET' && (/^\/comic\/[^/]+(?:\/chapter\/[^/]+)?\/?$/.test(target.path) ||
                /^\/comicdetail\/[^/]+\/chapters\/?$/.test(target.path) || /\.js$/i.test(target.path));
        }
        if (!['api.mangacopy.com', 'api.2025copy.com'].includes(target.host)) return false;
        if (method === 'POST') return target.host === 'api.mangacopy.com' && target.path === '/api/v3/member/roast';
        return method === 'GET' && (/^\/api\/v3\/comic\/[^/]+\/chapter\/[^/]+\/?$/.test(target.path) ||
            /^\/api\/v3\/comic2\/query\/[^/]+\/?$/.test(target.path) || target.path === '/api/v3/roasts');
    }

    if (incoming.path !== BRIDGE) {
        // A fresh document response is needed for injection; do not touch asset/API caching.
        if ($request.method === 'GET' && !/^api\./.test(incoming.host) &&
            (incoming.path === '/' || /^\/(?:comic|h5)(?:\/|$)/.test(incoming.path)) &&
            /text\/html/i.test(header($request.headers, 'accept'))) {
            const headers = Object.assign({}, $request.headers);
            Object.keys(headers).forEach(k => {
                if (['if-none-match', 'if-modified-since'].includes(k.toLowerCase())) delete headers[k];
            });
            return $done({ headers });
        }
        return $done({});
    }

    // A bridge request must be generated by our same-origin reader, never a navigation or cross-site form.
    if ($request.method !== 'POST' || !/^application\/json(?:\s*;|$)/i.test(header($request.headers, 'content-type'))) {
        return fail(405, '阅读器请求格式不正确');
    }
    const origin = header($request.headers, 'origin');
    const fetchSite = header($request.headers, 'sec-fetch-site');
    if ((origin && origin !== incoming.origin) || (fetchSite && fetchSite !== 'same-origin')) {
        return fail(403, '只接受当前站点的阅读器请求');
    }
    let payload;
    try {
        if (typeof $request.body !== 'string' || $request.body.length > 65536) throw new Error();
        payload = JSON.parse($request.body);
        if (!payload || typeof payload !== 'object') throw new Error();
    } catch (_) { return fail(400, '无法读取阅读器请求'); }
    const method = String(payload.method || 'GET').toUpperCase();
    const target = parseURL(payload.url);
    if (!allowed(target, method)) return fail(403, '该地址不属于阅读器接口');
    if (method === 'POST' && (typeof payload.data !== 'string' || payload.data.length > 32768)) {
        return fail(400, '评论内容格式不正确');
    }

    // One budget for the whole redirect chain; no automatic retries.
    const deadline = Date.now() + 24000;
    function fetchTarget(current, hops) {
        const remaining = deadline - Date.now();
        if (remaining <= 0) return fail(504, '上游请求超时，请手动重新加载');
        const headers = { 'User-Agent': UA, 'Referer': incoming.origin + '/', 'Accept': '*/*' };
        const supplied = payload.headers && typeof payload.headers === 'object' ? payload.headers : {};
        Object.keys(supplied).forEach(k => {
            const key = k.toLowerCase();
            if (!['accept', 'content-type', 'version', 'platform', 'dnts', 'authorization'].includes(key)) return;
            if (key === 'authorization' && current.host !== 'api.mangacopy.com') return;
            const value = String(supplied[k]);
            if (!/[\r\n]/.test(value)) headers[k] = value;
        });
        // Safari cookies are forwarded only back to the same host, never to an API/redirect host.
        const cookie = header($request.headers, 'cookie');
        if (current.host === incoming.host && cookie) headers.Cookie = cookie;
        const options = { url: current.url, headers, timeout: remaining, 'auto-redirect': false, 'auto-cookie': false, insecure: false };
        if (method === 'POST') options.body = payload.data;
        $httpClient[method.toLowerCase()](options, function (error, response, data) {
            if (error || !response) return fail(502, '上游请求失败，请检查网络后重试');
            const status = Number(response.status || response.statusCode);
            if ([301, 302, 303, 307, 308].includes(status)) {
                // Read-only redirects only; validate every hop rather than following an arbitrary Location.
                if (method !== 'GET' || hops >= 2) return fail(502, '上游重定向异常');
                const location = String(header(response.headers, 'location'));
                const next = parseURL(/^https:\/\//i.test(location) ? location :
                    location.startsWith('//') ? 'https:' + location :
                    location.startsWith('/') ? current.origin + location : '');
                if (!allowed(next, method)) return fail(502, '上游跳转到了阅读器范围以外的地址');
                return fetchTarget(next, hops + 1);
            }
            respond(200, { status, data: typeof data === 'string' ? data : '',
                contentType: String(header(response.headers, 'content-type')) });
        });
    }
    fetchTarget(target, 0);
})();
